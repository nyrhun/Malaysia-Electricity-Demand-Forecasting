# 1. import libraries, upload and load data

from pathlib import Path
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from scipy.linalg import lu
from sklearn.metrics import mean_squared_error, mean_absolute_error

data_path = Path(__file__).resolve().parent / "electricity_consumption.csv"
df = pd.read_csv(data_path)

# 2. inspect data

# Inspect data
df.info()
df.head()

# 3. data preprocessing

# Use TOTAL electricity consumption only
df = df[df["sector"] == "total"]

# Convert date column and sort
df["date"] = pd.to_datetime(df["date"])
df = df.sort_values("date")

# Drop missing values (if any)
df = df.dropna()

# Extract electricity consumption as time series
y = df["consumption"].astype(float).values

print("Total observations:", len(y))

# 4. descriptive statistics

desc_stats = df["consumption"].describe()
print(desc_stats)

# 5. build least squares matrices
#    xt = a1 xt-1 + a2 xt-2 + a3 xt-3

X = []
Y = []

for i in range(3, len(y)):
    X.append([y[i-1], y[i-2], y[i-3]])
    Y.append(y[i])

X = np.array(X)
Y = np.array(Y).reshape(-1, 1)

print("X shape:", X.shape)
print("Y shape:", Y.shape)

# 6. least squares normal equations
#    (X^T X)a = X^T y

XtX = X.T @ X
XtY = X.T @ Y

# 7. solve using LU decomposition

P, L, U = lu(XtX)

# Forward substitution
y1 = np.linalg.solve(L, P.T @ XtY)

# Backward substitution
coefficients = np.linalg.solve(U, y1)

a1, a2, a3 = coefficients.flatten()

print("Estimated coefficients:")
print("a1 =", a1)
print("a2 =", a2)
print("a3 =", a3)

# 8. transition matrix

M = np.array([
    [a1, a2, a3],
    [1,  0,  0 ],
    [0,  1,  0 ]
])

# 9. eigenvalue analysis

eigenvalues, eigenvectors = np.linalg.eig(M)
lambda_max = np.max(np.abs(eigenvalues))

print("Eigenvalues:", eigenvalues)
print("Largest eigenvalue:", lambda_max)

# 10. forecast next 12 months

x0 = y[-3:]  # last 3 known values
forecast = []

for i in range(12):
    x1 = a1*x0[2] + a2*x0[1] + a3*x0[0]
    forecast.append(x1)
    x0 = np.append(x0[1:], x1)

print("12-month forecast:")
for i, val in enumerate(forecast, 1):
    print(f"Month {i}: {val:.2f} GWh")

last_date = df["date"].iloc[-1]
future_dates = pd.date_range(start=last_date, periods=13, freq="MS")[1:]

#11. model predictions

Y_pred = X @ coefficients

# Error metrics
mse = mean_squared_error(Y, Y_pred)
mae = mean_absolute_error(Y, Y_pred)

print("In-sample Mean Squared Error (MSE):", mse)
print("In-sample Mean Absolute Error (MAE):", mae)

# Test on the last 12 months
X_train, X_test = X[:-12], X[-12:]
Y_train, Y_test = Y[:-12], Y[-12:]

# Fit the model using training data only
P_train, L_train, U_train = lu(X_train.T @ X_train)
rhs = X_train.T @ Y_train

intermediate = np.linalg.solve(L_train, P_train.T @ rhs)
test_coefficients = np.linalg.solve(U_train, intermediate)

# Predict each test month using its actual previous months
test_predictions = X_test @ test_coefficients

# Simple baseline: predict the same value as the previous month
baseline_predictions = X_test[:, 0].reshape(-1, 1)

print("\n--- Last 12 months: test results ---")
print("Model MAE:", mean_absolute_error(Y_test, test_predictions))
print("Previous-month baseline MAE:", mean_absolute_error(Y_test, baseline_predictions))

